-- 6. Defensa en profundidad para las mismas reglas que verifica el backend.
-- Los bloqueos siguen el orden usuario (ID ascendente) y luego paciente, igual
-- que las operaciones transaccionales de asignación/seguimiento del backend.
CREATE FUNCTION public.validar_asignacion_medico() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_usuario_paciente integer;
BEGIN
    -- Cerrar una asignación no depende de que el asignador siga activo.
    IF NOT NEW.activo THEN
        RETURN NEW;
    END IF;

    SELECT id_usuario INTO v_usuario_paciente
      FROM public.paciente WHERE id_paciente = NEW.id_paciente;
    IF v_usuario_paciente IS NULL THEN
        RAISE EXCEPTION 'Paciente inexistente para la asignación.';
    END IF;

    PERFORM u.id_usuario
      FROM public.usuario u
     WHERE u.id_usuario = ANY (ARRAY[NEW.id_usuario_asignador, NEW.id_medico, v_usuario_paciente])
     ORDER BY u.id_usuario FOR UPDATE;
    PERFORM p.id_paciente FROM public.paciente p
     WHERE p.id_paciente = NEW.id_paciente FOR UPDATE;

    IF NOT EXISTS (SELECT 1 FROM public.usuario WHERE id_usuario = NEW.id_usuario_asignador
                   AND rol = 'administrador' AND activo)
       OR NOT EXISTS (SELECT 1 FROM public.usuario WHERE id_usuario = NEW.id_medico
                      AND rol = 'medico' AND activo)
       OR NOT EXISTS (SELECT 1 FROM public.usuario WHERE id_usuario = v_usuario_paciente
                      AND rol = 'paciente' AND activo) THEN
        RAISE EXCEPTION 'Asignador, médico y paciente deben tener roles y estados activos válidos.';
    END IF;
    RETURN NEW;
END;
$$;

