-- Esquema inicial para una base PostgreSQL nueva y vacía.
-- No contiene datos iniciales ni elimina objetos existentes.
-- Crear el primer administrador por el procedimiento documentado en
-- backend/MIGRACIONES_Y_SEGURIDAD.md (bootstrap:admin); no mediante INSERT manual.

BEGIN;

-- 1. Cuentas y perfiles
CREATE TABLE public.usuario (
    id_usuario       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo           varchar(150) NOT NULL,
    contrasena_hash  varchar(255) NOT NULL,
    rol              varchar(20) NOT NULL DEFAULT 'paciente',
    activo           boolean NOT NULL DEFAULT false,
    fecha_creacion   timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuario_rol
        CHECK (rol IN ('paciente', 'medico', 'seguimiento', 'administrador'))
);

-- Login consulta lower(correo), por lo que la unicidad se aplica sin distinguir
-- mayúsculas/minúsculas. La aplicación almacena los correos normalizados.
CREATE UNIQUE INDEX uq_usuario_correo_ci ON public.usuario (lower(correo));

CREATE TABLE public.paciente (
    id_paciente        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario         integer NOT NULL UNIQUE,
    nombre             varchar(80) NOT NULL,
    apellido_paterno   varchar(80) NOT NULL,
    apellido_materno   varchar(80),
    fecha_nacimiento   date NOT NULL,
    telefono           varchar(20),
    telegram_chat_id   varchar(50),
    telegram_verificado boolean NOT NULL DEFAULT false,
    telegram_verificado_en timestamp without time zone,
    fecha_registro     timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT fk_paciente_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuario (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT ck_paciente_telegram_verificado CHECK (
        (NOT telegram_verificado AND telegram_verificado_en IS NULL)
        OR (telegram_verificado AND telegram_chat_id IS NOT NULL AND telegram_verificado_en IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_paciente_telegram_chat_verificado
    ON public.paciente (telegram_chat_id) WHERE telegram_verificado = true;

CREATE TABLE public.telegram_vinculo (
    id_vinculo       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_chat_id varchar(50) NOT NULL CHECK (telegram_chat_id ~ '^[0-9]{1,20}$'),
    codigo_hash      varchar(64) NOT NULL UNIQUE CHECK (codigo_hash ~ '^[0-9a-f]{64}$'),
    creado_en        timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    expira_en        timestamp without time zone NOT NULL,
    consumido_en     timestamp without time zone,
    CONSTRAINT ck_telegram_vinculo_expiracion CHECK (expira_en > creado_en),
    CONSTRAINT ck_telegram_vinculo_consumo CHECK (consumido_en IS NULL OR consumido_en >= creado_en)
);
CREATE INDEX idx_telegram_vinculo_pendiente
    ON public.telegram_vinculo (telegram_chat_id, expira_en) WHERE consumido_en IS NULL;

-- 2. Asignaciones con historial. La unicidad parcial permite conservar filas
-- cerradas y garantiza como máximo un profesional activo de cada tipo/paciente.
CREATE TABLE public.medico_paciente (
    id_asignacion         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medico             integer NOT NULL,
    id_paciente           integer NOT NULL,
    id_usuario_asignador  integer NOT NULL,
    fecha_asignacion      date NOT NULL DEFAULT CURRENT_DATE,
    activo                boolean NOT NULL DEFAULT true,
    CONSTRAINT fk_mp_medico FOREIGN KEY (id_medico)
        REFERENCES public.usuario (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT fk_mp_paciente FOREIGN KEY (id_paciente)
        REFERENCES public.paciente (id_paciente) ON DELETE RESTRICT,
    CONSTRAINT fk_mp_asignador FOREIGN KEY (id_usuario_asignador)
        REFERENCES public.usuario (id_usuario) ON DELETE RESTRICT
);

CREATE TABLE public.seguimiento_paciente (
    id_asignacion         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_seguimiento        integer NOT NULL,
    id_paciente           integer NOT NULL,
    id_usuario_asignador  integer NOT NULL,
    fecha_asignacion      date NOT NULL DEFAULT CURRENT_DATE,
    activo                boolean NOT NULL DEFAULT true,
    CONSTRAINT fk_sp_seguimiento FOREIGN KEY (id_seguimiento)
        REFERENCES public.usuario (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT fk_sp_paciente FOREIGN KEY (id_paciente)
        REFERENCES public.paciente (id_paciente) ON DELETE RESTRICT,
    CONSTRAINT fk_sp_asignador FOREIGN KEY (id_usuario_asignador)
        REFERENCES public.usuario (id_usuario) ON DELETE RESTRICT
