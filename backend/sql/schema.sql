-- 3. Datos clínicos y actividad de seguimiento
CREATE TABLE public.medicion (
    id_medicion       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente       integer NOT NULL,
    tipo              varchar(20) NOT NULL,
    glucosa_mg_dl     numeric(6,2),
    sistolica_mmhg    smallint,
    diastolica_mmhg   smallint,
    contexto          varchar(50),
    fecha_hora        timestamp without time zone NOT NULL,
    observaciones     text,
    fecha_registro    timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT ck_medicion_tipo
        CHECK (tipo IN ('glucosa', 'presion_arterial')),
    CONSTRAINT ck_medicion_valores CHECK (
        (tipo = 'glucosa'
            AND glucosa_mg_dl IS NOT NULL
            AND sistolica_mmhg IS NULL AND diastolica_mmhg IS NULL)
        OR
        (tipo = 'presion_arterial'
            AND sistolica_mmhg IS NOT NULL AND diastolica_mmhg IS NOT NULL
            AND glucosa_mg_dl IS NULL)
    ),
    CONSTRAINT fk_medicion_paciente FOREIGN KEY (id_paciente)
        REFERENCES public.paciente (id_paciente) ON DELETE RESTRICT
);
CREATE INDEX idx_medicion_paciente_fecha
    ON public.medicion (id_paciente, fecha_hora DESC);

CREATE TABLE public.medicamento (
