-- Vinculación verificable de chats privados de Telegram con cuentas paciente.
-- Los chat IDs existentes quedan sin verificar; sólo el flujo de código puede validarlos.
BEGIN;

ALTER TABLE public.paciente
  ADD COLUMN telegram_verificado boolean NOT NULL DEFAULT false,
  ADD COLUMN telegram_verificado_en timestamp without time zone;

ALTER TABLE public.paciente
  ADD CONSTRAINT ck_paciente_telegram_verificado CHECK (
    (NOT telegram_verificado AND telegram_verificado_en IS NULL)
    OR (telegram_verificado AND telegram_chat_id IS NOT NULL AND telegram_verificado_en IS NOT NULL)
  );

CREATE UNIQUE INDEX uq_paciente_telegram_chat_verificado
  ON public.paciente (telegram_chat_id) WHERE telegram_verificado = true;

CREATE TABLE public.telegram_vinculo (
  id_vinculo       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telegram_chat_id varchar(50) NOT NULL CHECK (telegram_chat_id ~ '^[0-9]{1,20}$'),
  codigo_hash      varchar(64) NOT NULL UNIQUE CHECK (codigo_hash ~ '^[0-9a-f]{64}$'),
  creado_en        timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  expira_en        timestamp without time zone NOT NULL,
  consumido_en     timestamp without time zone,
  CONSTRAINT ck_telegram_vinculo_expiracion CHECK (expira_en > creado_en),
  CONSTRAINT ck_telegram_vinculo_consumo CHECK (consumido_en IS NULL OR consumido_en >= creado_en)
);

CREATE INDEX idx_telegram_vinculo_pendiente
  ON public.telegram_vinculo (telegram_chat_id, expira_en) WHERE consumido_en IS NULL;

COMMIT;
