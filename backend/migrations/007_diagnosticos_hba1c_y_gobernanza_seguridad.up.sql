CREATE TABLE public.diagnostico (
  id_diagnostico integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_paciente integer NOT NULL,
  codigo varchar(30) NOT NULL,
  estado varchar(20) NOT NULL DEFAULT 'confirmado',
  confirmado_en date NOT NULL DEFAULT CURRENT_DATE,
  cerrado_en date,
  id_medico integer NOT NULL,
  creado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_diagnostico_codigo CHECK (codigo IN ('diabetes_tipo_1','diabetes_tipo_2','hipertension')),
  CONSTRAINT ck_diagnostico_estado CHECK (estado IN ('confirmado','cerrado')),
  CONSTRAINT ck_diagnostico_cierre CHECK ((estado='confirmado' AND cerrado_en IS NULL) OR (estado='cerrado' AND cerrado_en IS NOT NULL AND cerrado_en>=confirmado_en)),
  CONSTRAINT fk_diagnostico_paciente FOREIGN KEY (id_paciente) REFERENCES public.paciente(id_paciente) ON DELETE RESTRICT,
  CONSTRAINT fk_diagnostico_medico FOREIGN KEY (id_medico) REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX uq_diagnostico_activo ON public.diagnostico(id_paciente,codigo) WHERE estado='confirmado';
CREATE INDEX idx_diagnostico_paciente_historial ON public.diagnostico(id_paciente,confirmado_en DESC);

CREATE FUNCTION public.validar_diagnostico() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Los diagnósticos se conservan en el historial'; END IF;
  IF TG_OP='INSERT' THEN
    IF NEW.confirmado_en>CURRENT_DATE THEN RAISE EXCEPTION 'La fecha de diagnóstico no puede ser futura'; END IF;
    IF NOT EXISTS (SELECT 1 FROM public.usuario m JOIN public.medico_paciente mp ON mp.id_medico=m.id_usuario
      JOIN public.paciente p ON p.id_paciente=mp.id_paciente JOIN public.usuario up ON up.id_usuario=p.id_usuario
      WHERE m.id_usuario=NEW.id_medico AND m.activo AND m.rol='medico' AND mp.id_paciente=NEW.id_paciente AND mp.activo
        AND up.activo AND up.rol='paciente') THEN RAISE EXCEPTION 'Solo el médico activo asignado puede confirmar diagnósticos'; END IF;
    RETURN NEW;
  END IF;
  IF NEW.id_paciente IS DISTINCT FROM OLD.id_paciente OR NEW.codigo IS DISTINCT FROM OLD.codigo
     OR NEW.confirmado_en IS DISTINCT FROM OLD.confirmado_en OR NEW.id_medico IS DISTINCT FROM OLD.id_medico
     OR NEW.creado_en IS DISTINCT FROM OLD.creado_en OR OLD.estado<>'confirmado' OR NEW.estado<>'cerrado'
     OR NEW.cerrado_en IS NULL THEN RAISE EXCEPTION 'El diagnóstico es inmutable; solo se permite cerrarlo'; END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_validar_diagnostico BEFORE INSERT OR UPDATE OR DELETE ON public.diagnostico
  FOR EACH ROW EXECUTE FUNCTION public.validar_diagnostico();

