CREATE FUNCTION public.auditar_diagnostico() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_actor integer;
BEGIN
  BEGIN v_actor:=NULLIF(current_setting('app.usuario_actor',true),'')::integer; EXCEPTION WHEN OTHERS THEN v_actor:=NULL; END;
  IF TG_OP='INSERT' THEN
    INSERT INTO public.diagnostico_historial(id_diagnostico,actor_id_usuario,evento,estado_nuevo)
      VALUES(NEW.id_diagnostico,v_actor,'confirmado',NEW.estado);
  ELSIF NEW.estado IS DISTINCT FROM OLD.estado THEN
    INSERT INTO public.diagnostico_historial(id_diagnostico,actor_id_usuario,evento,estado_anterior,estado_nuevo)
      VALUES(NEW.id_diagnostico,v_actor,'cerrado',OLD.estado,NEW.estado);
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_auditar_diagnostico AFTER INSERT OR UPDATE OF estado ON public.diagnostico
  FOR EACH ROW EXECUTE FUNCTION public.auditar_diagnostico();
