CREATE TABLE public.revision_criterio_seguridad (
  id_revision bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_version_criterio integer NOT NULL,
  ronda smallint NOT NULL,
  id_revisor integer NOT NULL,
  id_autorizacion integer NOT NULL,
  decision varchar(24) NOT NULL,
