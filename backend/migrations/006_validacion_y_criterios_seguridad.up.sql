CREATE FUNCTION public.validar_revision_criterio_seguridad() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v version_criterio_seguridad%ROWTYPE;
BEGIN
  IF TG_OP <> 'INSERT' THEN RAISE EXCEPTION 'Las decisiones clinicas son inmutables'; END IF;
  SELECT * INTO v FROM public.version_criterio_seguridad WHERE id_version_criterio=NEW.id_version_criterio FOR UPDATE;
  IF v.estado <> 'en_revision' OR NEW.ronda <> v.ronda_actual OR NEW.id_revisor=v.autor_id_usuario THEN
    RAISE EXCEPTION 'Version, ronda o independencia de revision no validas';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.autorizacion_editorial a JOIN public.usuario u ON u.id_usuario=a.id_usuario
    WHERE a.id_autorizacion=NEW.id_autorizacion AND a.id_usuario=NEW.id_revisor AND a.capacidad='revisor'
      AND a.estado='activa' AND a.vigente_desde<=now() AND (a.vigente_hasta IS NULL OR a.vigente_hasta>now())
      AND u.activo AND u.rol='medico' FOR UPDATE OF a,u) THEN
    RAISE EXCEPTION 'Se requiere medico activo con autorizacion de revision vigente'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.alcance_editorial s WHERE s.id_autorizacion=NEW.id_autorizacion
    AND s.tipo_contenido='seguridad_medicion' AND (s.enfermedad IS NULL OR s.enfermedad=v.enfermedad)
    AND (s.poblacion IS NULL OR s.poblacion=v.poblacion)) THEN
    RAISE EXCEPTION 'El revisor no tiene alcance para este criterio de seguridad';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_validar_revision_criterio_seguridad BEFORE INSERT OR UPDATE OR DELETE
  ON public.revision_criterio_seguridad FOR EACH ROW EXECUTE FUNCTION public.validar_revision_criterio_seguridad();

CREATE FUNCTION public.validar_ciclo_criterio_seguridad() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE aprobadas integer; otras integer; fuente_vigente boolean;
BEGIN
  IF TG_OP='INSERT' THEN
    IF NEW.estado <> 'borrador' THEN RAISE EXCEPTION 'Un criterio nuevo inicia como borrador'; END IF;
    RETURN NEW;
  END IF;
  IF NEW.id_criterio IS DISTINCT FROM OLD.id_criterio OR NEW.numero_version IS DISTINCT FROM OLD.numero_version
     OR NEW.tipo_medicion IS DISTINCT FROM OLD.tipo_medicion OR NEW.unidad IS DISTINCT FROM OLD.unidad
     OR NEW.enfermedad IS DISTINCT FROM OLD.enfermedad OR NEW.poblacion IS DISTINCT FROM OLD.poblacion
     OR NEW.condicion IS DISTINCT FROM OLD.condicion OR NEW.mensaje_orientacion IS DISTINCT FROM OLD.mensaje_orientacion
     OR NEW.id_version_fuente IS DISTINCT FROM OLD.id_version_fuente OR NEW.autor_id_usuario IS DISTINCT FROM OLD.autor_id_usuario
     OR NEW.creado_en IS DISTINCT FROM OLD.creado_en OR NEW.ronda_actual IS DISTINCT FROM OLD.ronda_actual
     OR NEW.aprobado_en IS DISTINCT FROM OLD.aprobado_en OR NEW.activado_en IS DISTINCT FROM OLD.activado_en
     OR NEW.retirado_en IS DISTINCT FROM OLD.retirado_en THEN RAISE EXCEPTION 'Una version de criterio es inmutable'; END IF;
  IF NEW.estado IS NOT DISTINCT FROM OLD.estado THEN RAISE EXCEPTION 'Solo se permiten transiciones de estado'; END IF;
  IF OLD.estado='borrador' AND NEW.estado='en_revision' THEN
    NEW.ronda_actual:=OLD.ronda_actual+1; RETURN NEW;
  END IF;
  IF OLD.estado='en_revision' AND NEW.estado='borrador' THEN RETURN NEW; END IF;
  IF OLD.estado='en_revision' AND NEW.estado='aprobada' THEN
    SELECT count(DISTINCT id_revisor), count(*) FILTER (WHERE decision<>'aprobada') INTO aprobadas,otras
      FROM public.revision_criterio_seguridad WHERE id_version_criterio=OLD.id_version_criterio AND ronda=OLD.ronda_actual;
    IF aprobadas < 2 OR otras>0 THEN RAISE EXCEPTION 'Se requieren dos revisiones medicas independientes aprobadas en la ronda'; END IF;
    SELECT estado='vigente' INTO fuente_vigente FROM public.version_fuente vf JOIN public.fuente_clinica f USING(id_fuente)
      WHERE vf.id_version_fuente=NEW.id_version_fuente;
    IF NOT COALESCE(fuente_vigente,false) THEN RAISE EXCEPTION 'La fuente asociada no esta vigente'; END IF;
    NEW.aprobado_en:=now(); RETURN NEW;
  END IF;
  IF OLD.estado='aprobada' AND NEW.estado='activa' THEN
    IF NEW.activado_por IS NULL OR NEW.id_autorizacion_activador IS NULL OR NEW.activado_por=NEW.autor_id_usuario
       OR NOT EXISTS (SELECT 1 FROM public.usuario u JOIN public.autorizacion_editorial a ON a.id_usuario=u.id_usuario
         WHERE u.id_usuario=NEW.activado_por AND u.activo AND u.rol='medico'
           AND a.id_autorizacion=NEW.id_autorizacion_activador AND a.capacidad='publicador' AND a.estado='activa'
           AND a.vigente_desde<=now() AND (a.vigente_hasta IS NULL OR a.vigente_hasta>now())) THEN
      RAISE EXCEPTION 'Activar requiere medico publicador activo, vigente e independiente del autor';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.alcance_editorial s WHERE s.id_autorizacion=NEW.id_autorizacion_activador
      AND s.tipo_contenido='seguridad_medicion' AND (s.enfermedad IS NULL OR s.enfermedad=NEW.enfermedad)
      AND (s.poblacion IS NULL OR s.poblacion=NEW.poblacion)) THEN RAISE EXCEPTION 'Publicador fuera del alcance clinico'; END IF;
    SELECT estado='vigente' INTO fuente_vigente FROM public.version_fuente vf JOIN public.fuente_clinica f USING(id_fuente)
      WHERE vf.id_version_fuente=NEW.id_version_fuente;
    IF NOT COALESCE(fuente_vigente,false) THEN RAISE EXCEPTION 'La fuente asociada no esta vigente'; END IF;
    NEW.activado_en:=now(); RETURN NEW;
  END IF;
  IF OLD.estado IN ('aprobada','activa') AND NEW.estado='retirada' THEN
    IF NEW.motivo_retiro IS NULL OR length(btrim(NEW.motivo_retiro))=0 THEN RAISE EXCEPTION 'El retiro requiere motivo'; END IF;
    NEW.retirado_en:=now(); RETURN NEW;
  END IF;
  RAISE EXCEPTION 'Transicion de criterio no permitida: % -> %', OLD.estado, NEW.estado;
END; $$;
CREATE TRIGGER trg_ciclo_criterio_seguridad BEFORE INSERT OR UPDATE ON public.version_criterio_seguridad
  FOR EACH ROW EXECUTE FUNCTION public.validar_ciclo_criterio_seguridad();
