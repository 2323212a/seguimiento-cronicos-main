-- 006: validacion tecnica, trazabilidad y soporte para criterios de seguridad aprobados.
-- No contiene criterios ni mensajes clinicos precargados.
BEGIN;

DO $$
DECLARE n integer;
BEGIN
  SELECT count(*) INTO n FROM information_schema.tables
   WHERE table_schema='public' AND table_type='BASE TABLE';
  IF n <> 25 THEN RAISE EXCEPTION 'Precondicion 006: se esperaban 25 tablas, encontradas %', n; END IF;
  IF to_regclass('public.version_criterio_seguridad') IS NOT NULL
     OR to_regclass('public.evaluacion_medicion') IS NOT NULL THEN
    RAISE EXCEPTION 'Migracion 006 ya aplicada o sus objetos ya existen';
  END IF;
  IF EXISTS (SELECT 1 FROM public.medicion WHERE
       (tipo='glucosa' AND (glucosa_mg_dl<=0 OR sistolica_mmhg IS NOT NULL OR diastolica_mmhg IS NOT NULL)) OR
       (tipo='presion_arterial' AND (sistolica_mmhg<=0 OR diastolica_mmhg<=0 OR sistolica_mmhg<=diastolica_mmhg OR glucosa_mg_dl IS NOT NULL))) THEN
    RAISE EXCEPTION 'Precondicion 006: hay mediciones que incumplen la validacion tecnica; revisar antes de restringir nuevas capturas';
  END IF;
END $$;

ALTER TABLE public.medicion ADD CONSTRAINT ck_medicion_glucosa_positiva
  CHECK (tipo <> 'glucosa' OR glucosa_mg_dl > 0);
ALTER TABLE public.medicion ADD CONSTRAINT ck_medicion_presion_tecnica
  CHECK (tipo <> 'presion_arterial' OR (sistolica_mmhg > 0 AND diastolica_mmhg > 0 AND sistolica_mmhg > diastolica_mmhg));

CREATE TABLE public.criterio_seguridad (
  id_criterio integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(40) NOT NULL UNIQUE,
  nombre varchar(120) NOT NULL,
  creado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_criterio_seguridad_codigo CHECK (codigo ~ '^[a-z][a-z0-9_]{1,39}$')
);

CREATE TABLE public.version_criterio_seguridad (
  id_version_criterio integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_criterio integer NOT NULL,
  numero_version varchar(40) NOT NULL,
  tipo_medicion varchar(20) NOT NULL,
  unidad varchar(20) NOT NULL,
  enfermedad varchar(30),
  poblacion varchar(30) NOT NULL,
  condicion jsonb NOT NULL,
  mensaje_orientacion text NOT NULL,
  id_version_fuente integer NOT NULL,
  autor_id_usuario integer NOT NULL,
  estado varchar(20) NOT NULL DEFAULT 'borrador',
  ronda_actual smallint NOT NULL DEFAULT 0,
  aprobado_en timestamptz,
  activado_en timestamptz,
  activado_por integer,
  id_autorizacion_activador integer,
  retirado_en timestamptz,
  motivo_retiro text,
  creado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_version_criterio_numero UNIQUE (id_criterio, numero_version),
  CONSTRAINT uq_version_criterio_id UNIQUE (id_version_criterio, id_criterio),
  CONSTRAINT ck_version_criterio_medicion CHECK (
    (tipo_medicion='glucosa' AND unidad='mg/dL') OR
    (tipo_medicion='presion_arterial' AND unidad='mmHg')),
  CONSTRAINT ck_version_criterio_alcance_enfermedad CHECK (enfermedad IS NULL OR enfermedad IN ('diabetes_tipo_1','diabetes_tipo_2','hipertension')),
  CONSTRAINT ck_version_criterio_alcance_poblacion CHECK (poblacion IS NULL OR poblacion IN ('adolescente_13_17','adulto_18_mas')),
  CONSTRAINT ck_version_criterio_condicion CHECK (
    CASE WHEN jsonb_typeof(condicion)='object' AND jsonb_typeof(condicion->'any')='array'
      THEN jsonb_array_length(condicion->'any') BETWEEN 1 AND 20 ELSE false END),
  CONSTRAINT ck_version_criterio_mensaje CHECK (length(btrim(mensaje_orientacion)) BETWEEN 1 AND 2000),
  CONSTRAINT ck_version_criterio_estado CHECK (estado IN ('borrador','en_revision','aprobada','activa','retirada')),
  CONSTRAINT ck_version_criterio_ciclo CHECK (
    (estado IN ('borrador','en_revision') AND aprobado_en IS NULL AND activado_en IS NULL AND activado_por IS NULL AND retirado_en IS NULL)
    OR (estado='aprobada' AND aprobado_en IS NOT NULL AND activado_en IS NULL AND activado_por IS NULL AND retirado_en IS NULL)
    OR (estado='activa' AND aprobado_en IS NOT NULL AND activado_en IS NOT NULL AND activado_por IS NOT NULL AND retirado_en IS NULL)
    OR (estado='retirada' AND retirado_en IS NOT NULL AND motivo_retiro IS NOT NULL AND length(btrim(motivo_retiro))>0)),
  CONSTRAINT fk_version_criterio_catalogo FOREIGN KEY (id_criterio) REFERENCES public.criterio_seguridad(id_criterio) ON DELETE RESTRICT,
  CONSTRAINT fk_version_criterio_fuente FOREIGN KEY (id_version_fuente) REFERENCES public.version_fuente(id_version_fuente) ON DELETE RESTRICT,
  CONSTRAINT fk_version_criterio_autor FOREIGN KEY (autor_id_usuario) REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT,
  CONSTRAINT fk_version_criterio_activador FOREIGN KEY (activado_por) REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT,
  CONSTRAINT fk_version_criterio_auth_activador FOREIGN KEY (id_autorizacion_activador, activado_por)
    REFERENCES public.autorizacion_editorial(id_autorizacion,id_usuario) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX uq_version_criterio_activa ON public.version_criterio_seguridad(id_criterio) WHERE estado='activa';
CREATE INDEX idx_version_criterio_busqueda ON public.version_criterio_seguridad(tipo_medicion,enfermedad,poblacion,estado);

