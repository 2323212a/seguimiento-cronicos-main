-- 005: objetivos de medición definidos por el médico asignado y alertas fuera
-- del objetivo individual. No incluye umbrales predeterminados ni consejo de fármacos.
BEGIN;

DO $$
DECLARE v_count integer;
BEGIN
  SELECT count(*) INTO v_count FROM information_schema.tables
   WHERE table_schema='public' AND table_type='BASE TABLE'
     AND table_name = ANY(ARRAY['usuario','paciente','medico_paciente','seguimiento_paciente','medicion',
       'medicamento','horario_medicamento','alerta','seguimiento_accion','notificacion','reporte',
       'outbox_evento','evento_recibido','catalogo_medicion','version_catalogo','fuente_clinica',
       'version_fuente','autorizacion_editorial','alcance_editorial','ronda_revision',
       'revision_asignada','aprobacion_catalogo','catalogo_auditoria']);
  IF v_count <> 23 THEN
    RAISE EXCEPTION 'Precondición 005: se requieren las 23 tablas base/editoriales (encontradas %)', v_count;
  END IF;
  IF to_regclass('public.objetivo_medicion') IS NOT NULL THEN
    RAISE EXCEPTION 'Migración 005 ya aplicada o existe objetivo_medicion';
  END IF;
END $$;

CREATE TABLE public.objetivo_medicion (
  id_objetivo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_paciente integer NOT NULL,
  id_medico integer NOT NULL,
  tipo_medicion varchar(20) NOT NULL,
  contexto varchar(50),
  glucosa_min numeric(6,2),
  glucosa_max numeric(6,2),
  sistolica_min smallint,
  sistolica_max smallint,
  diastolica_min smallint,
  diastolica_max smallint,
  indicacion_paciente text NOT NULL,
  vigente_desde date NOT NULL DEFAULT CURRENT_DATE,
  vigente_hasta date,
  estado varchar(20) NOT NULL DEFAULT 'vigente',
  creado_en timestamptz NOT NULL DEFAULT now(),
  cerrado_en timestamptz,
  CONSTRAINT ck_objetivo_tipo CHECK (tipo_medicion IN ('glucosa','presion_arterial')),
  CONSTRAINT ck_objetivo_valores CHECK (
    (tipo_medicion='glucosa' AND (glucosa_min IS NOT NULL OR glucosa_max IS NOT NULL)
      AND (glucosa_min IS NULL OR glucosa_min > 0) AND (glucosa_max IS NULL OR glucosa_max > 0)
      AND (glucosa_min IS NULL OR glucosa_max IS NULL OR glucosa_min <= glucosa_max)
      AND sistolica_min IS NULL AND sistolica_max IS NULL AND diastolica_min IS NULL AND diastolica_max IS NULL)
    OR
    (tipo_medicion='presion_arterial' AND glucosa_min IS NULL AND glucosa_max IS NULL
      AND (sistolica_min IS NOT NULL OR sistolica_max IS NOT NULL OR diastolica_min IS NOT NULL OR diastolica_max IS NOT NULL)
      AND (sistolica_min IS NULL OR sistolica_min > 0) AND (sistolica_max IS NULL OR sistolica_max > 0)
      AND (diastolica_min IS NULL OR diastolica_min > 0) AND (diastolica_max IS NULL OR diastolica_max > 0)
      AND (sistolica_min IS NULL OR sistolica_max IS NULL OR sistolica_min <= sistolica_max)
      AND (diastolica_min IS NULL OR diastolica_max IS NULL OR diastolica_min <= diastolica_max))
  ),
  CONSTRAINT ck_objetivo_fechas CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde),
  CONSTRAINT ck_objetivo_estado CHECK (estado IN ('vigente','sustituido','retirado')),
  CONSTRAINT ck_objetivo_cierre CHECK ((estado='vigente' AND cerrado_en IS NULL) OR (estado<>'vigente' AND cerrado_en IS NOT NULL)),
  CONSTRAINT ck_objetivo_indicacion CHECK (length(btrim(indicacion_paciente)) BETWEEN 1 AND 2000),
  CONSTRAINT fk_objetivo_paciente FOREIGN KEY (id_paciente) REFERENCES public.paciente(id_paciente) ON DELETE RESTRICT,
  CONSTRAINT fk_objetivo_medico FOREIGN KEY (id_medico) REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX uq_objetivo_medicion_vigente
  ON public.objetivo_medicion(id_paciente,tipo_medicion,COALESCE(contexto,'')) WHERE estado='vigente';
CREATE INDEX idx_objetivo_paciente_fecha ON public.objetivo_medicion(id_paciente,estado,vigente_desde DESC);
CREATE INDEX idx_objetivo_medico ON public.objetivo_medicion(id_medico,estado);

CREATE FUNCTION public.validar_objetivo_medicion() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_activo boolean; v_rol varchar(20);
BEGIN
  IF TG_OP='INSERT' THEN
    IF length(btrim(NEW.indicacion_paciente))=0 THEN RAISE EXCEPTION 'La indicación del médico es obligatoria'; END IF;
    SELECT activo,rol INTO v_activo,v_rol FROM public.usuario WHERE id_usuario=NEW.id_medico;
    IF NOT COALESCE(v_activo,false) OR v_rol IS DISTINCT FROM 'medico' THEN
      RAISE EXCEPTION 'El objetivo debe registrarlo un médico activo';
    END IF;
    IF NOT EXISTS (
      SELECT 1 FROM public.medico_paciente mp
        JOIN public.paciente p ON p.id_paciente=mp.id_paciente
        JOIN public.usuario up ON up.id_usuario=p.id_usuario
       WHERE mp.id_paciente=NEW.id_paciente AND mp.id_medico=NEW.id_medico AND mp.activo
         AND up.activo AND up.rol='paciente') THEN
      RAISE EXCEPTION 'El médico debe tener asignación activa con el paciente';
    END IF;
    RETURN NEW;
  END IF;
  IF TG_OP='DELETE' THEN RAISE EXCEPTION 'El historial de objetivos no se elimina'; END IF;
  IF NEW.id_paciente IS DISTINCT FROM OLD.id_paciente OR NEW.id_medico IS DISTINCT FROM OLD.id_medico
     OR NEW.tipo_medicion IS DISTINCT FROM OLD.tipo_medicion OR NEW.contexto IS DISTINCT FROM OLD.contexto
     OR NEW.glucosa_min IS DISTINCT FROM OLD.glucosa_min OR NEW.glucosa_max IS DISTINCT FROM OLD.glucosa_max
     OR NEW.sistolica_min IS DISTINCT FROM OLD.sistolica_min OR NEW.sistolica_max IS DISTINCT FROM OLD.sistolica_max
     OR NEW.diastolica_min IS DISTINCT FROM OLD.diastolica_min OR NEW.diastolica_max IS DISTINCT FROM OLD.diastolica_max
     OR NEW.indicacion_paciente IS DISTINCT FROM OLD.indicacion_paciente
     OR NEW.vigente_desde IS DISTINCT FROM OLD.vigente_desde OR NEW.creado_en IS DISTINCT FROM OLD.creado_en THEN
    RAISE EXCEPTION 'El objetivo es inmutable; registre uno nuevo para sustituirlo';
  END IF;
  IF OLD.estado<>'vigente' OR NEW.estado NOT IN ('sustituido','retirado') OR NEW.cerrado_en IS NULL THEN
    RAISE EXCEPTION 'Sólo se puede cerrar una vez un objetivo vigente';
  END IF;
  IF NEW.vigente_hasta IS DISTINCT FROM OLD.vigente_hasta AND NEW.vigente_hasta IS NOT NULL
     AND NEW.vigente_hasta < OLD.vigente_desde THEN
    RAISE EXCEPTION 'La vigencia final no puede ser anterior al inicio';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_validar_objetivo_medicion BEFORE INSERT OR UPDATE OR DELETE ON public.objetivo_medicion
  FOR EACH ROW EXECUTE FUNCTION public.validar_objetivo_medicion();

ALTER TABLE public.alerta
  ADD COLUMN id_objetivo integer,
  ADD COLUMN clasificacion varchar(40),
  ADD COLUMN indicacion_paciente text,
  ADD CONSTRAINT fk_alerta_objetivo FOREIGN KEY (id_objetivo)
    REFERENCES public.objetivo_medicion(id_objetivo) ON DELETE RESTRICT,
  ADD CONSTRAINT ck_alerta_objetivo_datos CHECK (
    (id_objetivo IS NULL AND clasificacion IS NULL AND indicacion_paciente IS NULL)
    OR (id_objetivo IS NOT NULL AND id_medicion IS NOT NULL
        AND clasificacion='fuera_objetivo_individual'
        AND indicacion_paciente IS NOT NULL AND length(btrim(indicacion_paciente)) > 0)
  );
CREATE UNIQUE INDEX uq_alerta_objetivo_medicion
  ON public.alerta(id_medicion,id_objetivo) WHERE id_medicion IS NOT NULL AND id_objetivo IS NOT NULL;
CREATE INDEX idx_alerta_revision ON public.alerta(id_paciente,estado,fecha_generacion DESC);

CREATE TABLE public.alerta_historial (
  id_historial bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_alerta integer NOT NULL,
  actor_id_usuario integer,
  tipo_evento varchar(20) NOT NULL,
  estado_anterior varchar(20),
  estado_nuevo varchar(20) NOT NULL,
  ocurrido_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_alerta_historial_evento CHECK (tipo_evento IN ('generada','cambio_estado','migracion')),
  CONSTRAINT fk_alerta_historial_alerta FOREIGN KEY (id_alerta) REFERENCES public.alerta(id_alerta) ON DELETE RESTRICT,
  CONSTRAINT fk_alerta_historial_actor FOREIGN KEY (actor_id_usuario) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL
);
CREATE INDEX idx_alerta_historial_alerta ON public.alerta_historial(id_alerta,ocurrido_en);
INSERT INTO public.alerta_historial(id_alerta,tipo_evento,estado_nuevo)
SELECT id_alerta,'migracion',estado FROM public.alerta;

CREATE FUNCTION public.registrar_historial_alerta() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_actor integer; v_estado_anterior varchar(20);
BEGIN
  BEGIN v_actor := NULLIF(current_setting('app.usuario_actor',true),'')::integer;
  EXCEPTION WHEN OTHERS THEN v_actor := NULL; END;
  IF TG_OP='INSERT' THEN
    INSERT INTO public.alerta_historial(id_alerta,actor_id_usuario,tipo_evento,estado_nuevo)
      VALUES (NEW.id_alerta,v_actor,'generada',NEW.estado);
    RETURN NEW;
  END IF;
  IF NEW.estado IS DISTINCT FROM OLD.estado THEN
    INSERT INTO public.alerta_historial(id_alerta,actor_id_usuario,tipo_evento,estado_anterior,estado_nuevo)
      VALUES (NEW.id_alerta,v_actor,'cambio_estado',OLD.estado,NEW.estado);
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_historial_alerta_insert AFTER INSERT ON public.alerta
  FOR EACH ROW EXECUTE FUNCTION public.registrar_historial_alerta();
CREATE TRIGGER trg_historial_alerta_estado AFTER UPDATE OF estado ON public.alerta
  FOR EACH ROW EXECUTE FUNCTION public.registrar_historial_alerta();
CREATE FUNCTION public.inmutabilidad_historial_alerta() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'El historial de alertas es inmutable'; END; $$;
CREATE TRIGGER trg_historial_alerta_inmutable BEFORE UPDATE OR DELETE ON public.alerta_historial
  FOR EACH ROW EXECUTE FUNCTION public.inmutabilidad_historial_alerta();

COMMIT;
