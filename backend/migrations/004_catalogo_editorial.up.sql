-- Migracion 004: gobernanza editorial del catalogo.
-- No modifica ninguna de las 13 tablas existentes ni instala reglas clinicas.
BEGIN;

DO $$
DECLARE v_tipo text; v_tabla text;
BEGIN
  IF to_regclass('public.usuario') IS NULL THEN
    RAISE EXCEPTION 'Precondicion incumplida: falta public.usuario';
  END IF;
  SELECT format_type(a.atttypid, a.atttypmod) INTO v_tipo
    FROM pg_attribute a
   WHERE a.attrelid = 'public.usuario'::regclass AND a.attname = 'id_usuario' AND NOT a.attisdropped;
  IF v_tipo IS DISTINCT FROM 'integer' THEN
    RAISE EXCEPTION 'Precondicion incumplida: usuario.id_usuario debe ser integer (actual: %)', v_tipo;
  END IF;
  IF to_regclass('public.paciente') IS NULL OR to_regclass('public.medicion') IS NULL
     OR to_regclass('public.alerta') IS NULL THEN
    RAISE EXCEPTION 'Precondicion incumplida: esquema base incompleto';
  END IF;
  FOREACH v_tabla IN ARRAY ARRAY['usuario','paciente','medico_paciente','seguimiento_paciente','medicion',
    'medicamento','horario_medicamento','alerta','seguimiento_accion','notificacion','reporte','outbox_evento','evento_recibido'] LOOP
    IF to_regclass('public.' || v_tabla) IS NULL THEN
      RAISE EXCEPTION 'Precondicion incumplida: falta la tabla base public.%', v_tabla;
    END IF;
  END LOOP;
  IF to_regclass('public.catalogo_medicion') IS NOT NULL THEN
    RAISE EXCEPTION 'Migracion 004 ya aplicada o existe public.catalogo_medicion';
  END IF;
END $$;

CREATE TABLE public.catalogo_medicion (
