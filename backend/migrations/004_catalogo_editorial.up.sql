CREATE FUNCTION public.validar_aprobacion_editorial() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_autorizacion public.autorizacion_editorial%ROWTYPE; v_autor integer; v_estado_ronda varchar(20); v_activo boolean;
BEGIN
  SELECT estado INTO v_estado_ronda FROM public.ronda_revision WHERE id_ronda=NEW.id_ronda FOR UPDATE;
  IF v_estado_ronda IS DISTINCT FROM 'abierta' THEN RAISE EXCEPTION 'La ronda no está abierta'; END IF;
  SELECT autor_id_usuario INTO v_autor FROM public.version_catalogo WHERE id_version=NEW.id_version;
  IF v_autor IS NULL OR v_autor=NEW.id_revisor THEN RAISE EXCEPTION 'El autor no puede aprobar su propia versión'; END IF;
  SELECT activo INTO v_activo FROM public.usuario WHERE id_usuario=NEW.id_revisor FOR UPDATE;
  SELECT * INTO v_autorizacion FROM public.autorizacion_editorial WHERE id_autorizacion=NEW.id_autorizacion FOR UPDATE;
  IF NOT COALESCE(v_activo,false) OR v_autorizacion.id_usuario<>NEW.id_revisor OR v_autorizacion.capacidad<>'revisor'
     OR v_autorizacion.estado<>'activa' OR v_autorizacion.vigente_desde>now()
     OR (v_autorizacion.vigente_hasta IS NOT NULL AND v_autorizacion.vigente_hasta<=now()) THEN
    RAISE EXCEPTION 'Revisor sin autorización editorial vigente o cuenta activa';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.revision_asignada ra WHERE ra.id_ronda=NEW.id_ronda
      AND ra.id_revisor=NEW.id_revisor AND ra.id_autorizacion=NEW.id_autorizacion AND ra.estado IN ('asignada','en_revision')) THEN
    RAISE EXCEPTION 'El revisor no tiene asignación válida en la ronda';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.alcance_editorial ae JOIN public.version_catalogo vc ON vc.id_version=NEW.id_version
      WHERE ae.id_autorizacion=NEW.id_autorizacion AND ae.tipo_contenido=vc.tipo_contenido
      AND (ae.id_catalogo IS NULL OR ae.id_catalogo=vc.id_catalogo)
      AND (ae.enfermedad IS NULL OR ae.enfermedad=vc.enfermedad)
      AND (ae.poblacion IS NULL OR ae.poblacion=vc.poblacion)) THEN
    RAISE EXCEPTION 'El alcance editorial no corresponde a la versión';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_validar_aprobacion_editorial BEFORE INSERT ON public.aprobacion_catalogo
  FOR EACH ROW EXECUTE FUNCTION public.validar_aprobacion_editorial();

CREATE FUNCTION public.proteger_snapshot_editorial() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_estado varchar(20); v_id integer;
BEGIN
  IF TG_OP='DELETE' THEN v_id := OLD.id_version; ELSE v_id := NEW.id_version; END IF;
  SELECT estado INTO v_estado FROM public.version_catalogo WHERE id_version=v_id;
  IF v_estado IS DISTINCT FROM 'borrador' THEN RAISE EXCEPTION 'Snapshots bloqueados desde que la versión sale de borrador'; END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  IF TG_OP='UPDATE' THEN RAISE EXCEPTION 'Reemplace el snapshot mediante una nueva versión'; END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_snapshot_editorial_inmutable BEFORE INSERT OR UPDATE OR DELETE ON public.version_fuente
  FOR EACH ROW EXECUTE FUNCTION public.proteger_snapshot_editorial();

CREATE FUNCTION public.proteger_version_catalogo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.id_catalogo IS DISTINCT FROM OLD.id_catalogo OR NEW.numero_version IS DISTINCT FROM OLD.numero_version
     OR NEW.tipo_contenido IS DISTINCT FROM OLD.tipo_contenido OR NEW.enfermedad IS DISTINCT FROM OLD.enfermedad
     OR NEW.poblacion IS DISTINCT FROM OLD.poblacion OR NEW.autor_id_usuario IS DISTINCT FROM OLD.autor_id_usuario
     OR NEW.creada_en IS DISTINCT FROM OLD.creada_en THEN
    IF OLD.estado <> 'borrador' THEN RAISE EXCEPTION 'Una versión enviada a revisión no puede editarse; cree otra versión'; END IF;
  END IF;
  IF NEW.enviada_revision_en IS DISTINCT FROM OLD.enviada_revision_en AND NOT (OLD.estado='borrador' AND NEW.estado='en_revision') THEN
    RAISE EXCEPTION 'Fecha de envío a revisión inmutable';
  END IF;
  IF (NEW.publicada_en IS DISTINCT FROM OLD.publicada_en OR NEW.publicada_por IS DISTINCT FROM OLD.publicada_por)
     AND NOT (OLD.estado='aprobada' AND NEW.estado='vigente') THEN
    RAISE EXCEPTION 'Datos de publicación sólo se asignan durante publicación';
  END IF;
  IF NEW.sustituye_a IS DISTINCT FROM OLD.sustituye_a AND NOT (OLD.estado='aprobada' AND NEW.estado='vigente') THEN
    RAISE EXCEPTION 'La relación de sustitución sólo se fija al publicar';
  END IF;
  IF NEW.motivo_terminal IS DISTINCT FROM OLD.motivo_terminal AND NOT (NEW.estado IN ('retirada','cancelada') AND OLD.estado NOT IN ('retirada','cancelada')) THEN
    RAISE EXCEPTION 'Motivo terminal sólo se fija al retirar o cancelar';
  END IF;
  IF NEW.estado IS DISTINCT FROM OLD.estado AND NOT (
    (OLD.estado='borrador' AND NEW.estado IN ('en_revision','cancelada')) OR
    (OLD.estado='en_revision' AND NEW.estado IN ('aprobada','cancelada')) OR
    (OLD.estado='aprobada' AND NEW.estado IN ('vigente','retirada','cancelada')) OR
    (OLD.estado='vigente' AND NEW.estado IN ('sustituida','retirada')) OR
    (OLD.estado='sustituida' AND NEW.estado='retirada')) THEN
    RAISE EXCEPTION 'Transición de versión no permitida';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_proteger_version_catalogo BEFORE UPDATE ON public.version_catalogo
  FOR EACH ROW EXECUTE FUNCTION public.proteger_version_catalogo();

CREATE FUNCTION public.proteger_aprobacion_ronda() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.id_version IS DISTINCT FROM OLD.id_version OR NEW.numero_ronda IS DISTINCT FROM OLD.numero_ronda
     OR NEW.abierta_por IS DISTINCT FROM OLD.abierta_por OR NEW.abierta_en IS DISTINCT FROM OLD.abierta_en THEN
    RAISE EXCEPTION 'La identidad de una ronda es inmutable';
  END IF;
  IF OLD.estado<>'abierta' AND NEW.estado IS DISTINCT FROM OLD.estado THEN RAISE EXCEPTION 'Ronda cerrada es inmutable'; END IF;
  IF OLD.estado<>'abierta' AND (NEW.cerrada_por IS DISTINCT FROM OLD.cerrada_por OR NEW.cerrada_en IS DISTINCT FROM OLD.cerrada_en OR NEW.motivo_cierre IS DISTINCT FROM OLD.motivo_cierre) THEN
    RAISE EXCEPTION 'Datos de cierre de ronda inmutables';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_ronda_cerrada_inmutable BEFORE UPDATE ON public.ronda_revision
  FOR EACH ROW EXECUTE FUNCTION public.proteger_aprobacion_ronda();

CREATE FUNCTION public.proteger_revision_asignada() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN RAISE EXCEPTION 'La asignación histórica de revisión no se elimina'; END IF;
  IF NEW.id_ronda IS DISTINCT FROM OLD.id_ronda OR NEW.id_revisor IS DISTINCT FROM OLD.id_revisor
     OR NEW.id_autorizacion IS DISTINCT FROM OLD.id_autorizacion OR NEW.asignada_por IS DISTINCT FROM OLD.asignada_por
     OR NEW.asignada_en IS DISTINCT FROM OLD.asignada_en THEN
    RAISE EXCEPTION 'La asignación de revisión es inmutable';
  END IF;
  IF OLD.completada_en IS NOT NULL AND NEW.completada_en IS DISTINCT FROM OLD.completada_en THEN RAISE EXCEPTION 'Fecha de finalización inmutable'; END IF;
  IF NOT ((OLD.estado='asignada' AND NEW.estado IN ('en_revision','completada','retirada')) OR
          (OLD.estado='en_revision' AND NEW.estado IN ('completada','retirada')) OR
          (OLD.estado=NEW.estado)) THEN RAISE EXCEPTION 'Transición de revisión asignada no permitida'; END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_proteger_revision_asignada BEFORE UPDATE OR DELETE ON public.revision_asignada
  FOR EACH ROW EXECUTE FUNCTION public.proteger_revision_asignada();

