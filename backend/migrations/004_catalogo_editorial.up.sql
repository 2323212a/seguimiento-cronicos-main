CREATE FUNCTION public.validar_autorizacion_editorial() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_rol varchar(20); v_activo boolean;
BEGIN
  IF TG_OP='INSERT' THEN
    IF NEW.id_usuario=NEW.concedida_por THEN RAISE EXCEPTION 'No se permite autoconcesión editorial'; END IF;
    SELECT rol,activo INTO v_rol,v_activo FROM public.usuario WHERE id_usuario=NEW.concedida_por FOR UPDATE;
    IF v_rol IS DISTINCT FROM 'administrador' OR NOT COALESCE(v_activo,false) THEN
      RAISE EXCEPTION 'La concesión requiere un administrador activo';
    END IF;
    SELECT activo INTO v_activo FROM public.usuario WHERE id_usuario=NEW.id_usuario FOR UPDATE;
    IF NOT COALESCE(v_activo,false) THEN RAISE EXCEPTION 'El usuario autorizado debe estar activo'; END IF;
    RETURN NEW;
  END IF;
  IF NEW.id_usuario IS DISTINCT FROM OLD.id_usuario OR NEW.capacidad IS DISTINCT FROM OLD.capacidad
     OR NEW.concedida_por IS DISTINCT FROM OLD.concedida_por OR NEW.concedida_en IS DISTINCT FROM OLD.concedida_en
     OR NEW.vigente_desde IS DISTINCT FROM OLD.vigente_desde OR NEW.vigente_hasta IS DISTINCT FROM OLD.vigente_hasta
     OR NEW.referencia_evidencia IS DISTINCT FROM OLD.referencia_evidencia THEN
    RAISE EXCEPTION 'Una autorización concedida no se edita; la renovación crea otra autorización';
  END IF;
  IF OLD.estado <> 'activa' OR NEW.estado <> 'revocada' OR NEW.revocada_en IS NULL OR NEW.revocada_por IS NULL
     OR NEW.motivo_revocacion IS NULL OR length(btrim(NEW.motivo_revocacion))=0 THEN
    RAISE EXCEPTION 'Sólo se permite revocar una autorización activa con motivo';
  END IF;
  SELECT rol,activo INTO v_rol,v_activo FROM public.usuario WHERE id_usuario=NEW.revocada_por FOR UPDATE;
  IF v_rol IS DISTINCT FROM 'administrador' OR NOT COALESCE(v_activo,false) THEN
    RAISE EXCEPTION 'La revocación requiere un administrador activo';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_validar_autorizacion_editorial BEFORE INSERT OR UPDATE ON public.autorizacion_editorial
  FOR EACH ROW EXECUTE FUNCTION public.validar_autorizacion_editorial();

