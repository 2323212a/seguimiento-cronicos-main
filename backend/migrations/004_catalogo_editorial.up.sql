);
CREATE FUNCTION public.validar_estado_catalogo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.estado IS DISTINCT FROM OLD.estado AND NOT (OLD.estado='borrador' AND NEW.estado IN ('activo','retirado') OR OLD.estado='activo' AND NEW.estado='retirado') THEN
    RAISE EXCEPTION 'Transición de catálogo no permitida';
  END IF;
  IF NEW.codigo IS DISTINCT FROM OLD.codigo THEN RAISE EXCEPTION 'El código de catálogo es inmutable'; END IF;
  IF OLD.estado <> 'borrador' AND (NEW.nombre IS DISTINCT FROM OLD.nombre OR NEW.descripcion IS DISTINCT FROM OLD.descripcion OR NEW.unidad_base IS DISTINCT FROM OLD.unidad_base) THEN
    RAISE EXCEPTION 'Los metadatos publicados requieren una nueva versión';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_validar_estado_catalogo BEFORE UPDATE ON public.catalogo_medicion
  FOR EACH ROW EXECUTE FUNCTION public.validar_estado_catalogo();

